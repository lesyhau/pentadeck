"""Writes every logo file from design/mark.py and the Orbitron font.

    python design/build_logo.py          (from the repo root, with Pillow and fontTools)

Outputs:
  design/pentadeck-mark.svg                 the mark, 512 grid
  design/pentadeck-lockup-dark.svg          mark + wordmark, for dark backgrounds
  design/pentadeck-lockup-light.svg         mark + wordmark, for light backgrounds
  design/png/pentadeck-mark-<n>.png         16 .. 1024 px, transparent
  design/png/social-preview.png             1280 x 640, for the repository's social card
  webui/src/brand/Mark.tsx, favicon.svg, apple-touch-icon.png
The wordmark is drawn as outlines, so the SVGs need no font.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from fontTools.pens.svgPathPen import SVGPathPen          # noqa: E402
from fontTools.pens.transformPen import TransformPen      # noqa: E402
from fontTools.ttLib import TTFont                        # noqa: E402
from fontTools.varLib import instancer                    # noqa: E402
from PIL import Image                                     # noqa: E402

from design import mark as M                              # noqa: E402

DESIGN = ROOT / "design"
BRAND = ROOT / "webui" / "src" / "brand"
FONT = ROOT / "assets" / "fonts" / "Orbitron.ttf"
WORD = "PENTADECK"
TRACKING = 0.08               # letter-spacing, in em
INK_ON_DARK, INK_ON_LIGHT = "#E6EDF0", "#0F1B21"
CANVAS_DARK = "#0B0F12"
HEADER = "Pentadeck mark - generated by design/build_logo.py from design/mark.py; edit those, not this."


def wordmark(cap_px: float, x: float, baseline: float):
    """The wordmark as one SVG path 'd' with its width, set so its cap height is cap_px."""
    font = instancer.instantiateVariableFont(TTFont(FONT), {"wght": 700})
    cmap, gs, hmtx = font.getBestCmap(), font.getGlyphSet(), font["hmtx"]
    upem, cap = font["head"].unitsPerEm, font["OS/2"].sCapHeight
    k = cap_px / cap
    pen = SVGPathPen(gs, ntos=lambda v: M._f(v))
    pos = 0.0
    for i, ch in enumerate(WORD):
        name = cmap[ord(ch)]
        tp = TransformPen(pen, (k, 0, 0, -k, x + pos, baseline))
        gs[name].draw(tp)
        pos += hmtx[name][0] * k
        if i < len(WORD) - 1:
            pos += TRACKING * upem * k
    return pen.getCommands(), pos


def lockup(ink: str) -> str:
    """Mark on the left, the wordmark centred on it."""
    size = 512                                    # the mark's square
    left = M.INK[0]                               # trim the square's empty margin on the left
    cap = 150.0
    gap = 64.0
    tx = M.INK[2] + gap
    baseline = (M.INK[1] + M.INK[3]) / 2 + cap / 2   # the caps sit centred on the mark
    d, w = wordmark(cap, tx, baseline)
    vb_w = tx + w - left + 8
    body = "\n  ".join(M.svg_parts(0, 0, size))
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{M._f(left - 8)} 0 {M._f(vb_w + 8)} {size}">\n'
            f'  <!-- {HEADER} -->\n  {body}\n  <path d="{d}" fill="{ink}"/>\n</svg>\n')


def mark_tsx() -> str:
    els = "\n      ".join(e.replace("fill-rule=", "fillRule=").replace("/>", " />") for e in M.svg_parts())
    return f"""// GENERATED by design/build_logo.py from design/mark.py - edit those, not this.
// The Pentadeck mark: a pentagon in concentric rings; five wings, one per screen.
export function Mark({{ size = 28, className, title = 'Pentadeck' }}: {{ size?: number; className?: string; title?: string }}) {{
  return (
    <svg viewBox="0 0 {M.BOX} {M.BOX}" width={{size}} height={{size}} className={{className}} role="img" aria-label={{title}}>
      {els}
    </svg>
  )
}}
"""


def social_preview():
    """1280 x 640: the mark and the wordmark centred as a group, with a one-line tagline."""
    from PIL import ImageDraw, ImageFont
    W, H, MARK = 1280, 640, 380
    im = Image.new("RGBA", (W, H), M.rgb(CANVAS_DARK) + (255,))
    word = ImageFont.truetype(str(FONT), 92)
    word.set_variation_by_axes([700])
    sub = ImageFont.truetype(str(ROOT / "assets" / "fonts" / "Inter-Medium.ttf"), 30)
    tagline = "Open cockpit firmware for the Divoom Times Gate"
    track = 92 * TRACKING
    word_w = sum(word.getlength(ch) for ch in WORD) + track * (len(WORD) - 1)
    text_w = max(word_w, sub.getlength(tagline))
    k = MARK / M.BOX
    left_trim, right_end = k * M.INK[0], k * M.INK[2]              # the mark's ink inside its square
    gap = 60
    group = (right_end - left_trim) + gap + text_w
    x0 = (W - group) / 2 - left_trim
    m = M.render(MARK)
    im.paste(m, (round(x0), (H - MARK) // 2), m)
    d = ImageDraw.Draw(im)
    tx, cy = x0 + right_end + gap, H / 2 + k * ((M.INK[1] + M.INK[3]) / 2 - M.BOX / 2)
    x = tx
    for ch in WORD:
        d.text((x, cy - 18), ch, font=word, fill=M.rgb(INK_ON_DARK), anchor="ls")
        x += word.getlength(ch) + track
    d.text((tx + 2, cy + 40), tagline, font=sub, fill=(150, 170, 178), anchor="ls")
    return im.convert("RGB")


def main():
    (DESIGN / "png").mkdir(parents=True, exist_ok=True)
    BRAND.mkdir(parents=True, exist_ok=True)
    svg = M.svg_mark(HEADER)
    (DESIGN / "pentadeck-mark.svg").write_text(svg, encoding="utf-8")
    (DESIGN / "pentadeck-lockup-dark.svg").write_text(lockup(INK_ON_DARK), encoding="utf-8")
    (DESIGN / "pentadeck-lockup-light.svg").write_text(lockup(INK_ON_LIGHT), encoding="utf-8")
    for n in (16, 32, 48, 64, 128, 256, 512, 1024):
        M.render(n).save(DESIGN / "png" / f"pentadeck-mark-{n}.png")
    social_preview().save(DESIGN / "png" / "social-preview.png")

    (BRAND / "Mark.tsx").write_text(mark_tsx(), encoding="utf-8", newline="\n")
    (BRAND / "favicon.svg").write_text(svg, encoding="utf-8", newline="\n")
    # iOS rounds the corners itself; the mark sits on the dark canvas at 72 %
    touch = Image.new("RGBA", (180, 180), M.rgb(CANVAS_DARK) + (255,))
    m = M.render(130)
    touch.paste(m, (25, 25), m)
    touch.convert("RGB").save(BRAND / "apple-touch-icon.png", optimize=True)
    print("logo files written")


if __name__ == "__main__":
    main()
