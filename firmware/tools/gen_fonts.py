"""Pre-render the fonts for the firmware's own renderer (hud.c).

    python firmware/tools/gen_fonts.py      (from the repo root, with Pillow)

Glyphs (Inter for UI text, Orbitron for numbers and titles, from assets/fonts) are drawn by
FreeType at whole-pixel sizes and stored as 8-bit coverage bitmaps.
Writes main/assets/fonts.c and main/assets/fonts.h.
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
FW = HERE.parent
sys.path.insert(0, str(HERE))

from PIL import Image, ImageDraw  # noqa: E402

from draw import font  # noqa: E402

OUT = FW / "main" / "assets"
ASCII = list(range(0x20, 0x7F))
EXTRA = [0xB0, 0xB7, 0x2013, 0x2014, 0x2026]          # ° · – — …  (hud.c maps these in this order)

# name: (size, weight, family[, only these characters get pixels - the rest keep their advance])
BIG = "0123456789:.-+ABCDEFG#bm"
FONTS = {
    "b7": (7, 700, "ui"), "b8": (8, 700, "ui"), "b9": (9, 700, "ui"), "b12": (12, 700, "ui"),
    "sb9": (9, 600, "ui"), "sb11": (11, 600, "ui"),
    "o14": (14, 700, "brand"), "o16": (16, 700, "brand"), "o22": (22, 700, "brand"), "o28": (28, 700, "brand"),
    "o48": (48, 700, "brand", BIG),
}


def emit_font(name: str, size: int, weight: int, family: str, only: str | None = None) -> str:
    f = font(size, weight, family)
    ascent, descent = f.getmetrics()
    bitmap = bytearray()
    glyphs = []
    for cp in ASCII + EXTRA:
        ch = chr(cp)
        adv16 = round(f.getlength(ch) * 16)
        x0, y0, x1, y1 = f.getbbox(ch)          # origin at the ascender line (anchor "la")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        off = len(bitmap)
        if only is not None and ch not in only:
            w = h = 0
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-x0, -y0), ch, font=f, fill=255)
            bitmap += im.tobytes()
        top = y0 - ascent                       # glyph top relative to the baseline (negative = above)
        assert w < 256 and h < 256 and -128 <= x0 < 128 and -128 <= top < 128 and adv16 < 65536
        glyphs.append(f"{{ {off}, {w}, {h}, {x0}, {top}, {adv16} }}")
    rows = [", ".join(str(b) for b in bitmap[i:i + 32]) for i in range(0, len(bitmap), 32)] or ["0"]
    return f"""
/* {name}: {family} {weight} at {size} px; ascent {ascent}, descent {descent} */
static const uint8_t {name}_bitmap[] = {{
    {",\n    ".join(rows)}
}};
static const hud_glyph_t {name}_glyphs[{len(glyphs)}] = {{
    {",\n    ".join(glyphs)}
}};
const hud_font_t font_{name} = {{ {ascent}, {descent}, {name}_glyphs, {name}_bitmap }};
"""


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    body = ["/* Generated by tools/gen_fonts.py from assets/fonts. Do not edit. */",
            '#include "fonts.h"']
    for name, spec in FONTS.items():
        body.append(emit_font(name, *spec))
    (OUT / "fonts.c").write_text("\n".join(body), encoding="utf-8")
    header = ["/* Generated by tools/gen_fonts.py. Do not edit. */", "#pragma once", '#include "hud.h"', ""]
    for name, (size, weight, family, *only) in FONTS.items():
        note = f", only {only[0]}" if only else ""
        header.append(f"extern const hud_font_t font_{name};   /* {family} {weight}, {size} px{note} */")
    (OUT / "fonts.h").write_text("\n".join(header) + "\n", encoding="utf-8")
    print(f"wrote {len(FONTS)} fonts to {OUT / 'fonts.c'}")


if __name__ == "__main__":
    main()
