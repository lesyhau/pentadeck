"""Generate the firmware's images: the logo emblem animation and the weather icons.

    python firmware/tools/gen_assets.py      (from the repo root, with Pillow)

Writes main/assets/images.c / .h as big-endian RGB565 (the panels' byte order) on black.
The emblem is the Pentadeck mark (design/mark.py) with a light travelling round its five wings. Fonts come from gen_fonts.py.
"""
from __future__ import annotations

import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
FW = HERE.parent
sys.path.insert(0, str(FW.parent))          # the repo root, for design/
sys.path.insert(0, str(HERE))

from design import mark                      # noqa: E402
from draw import CANVAS, Canvas, weather     # noqa: E402

OUT = FW / "main" / "assets"
EMBLEM_FRAMES, EMBLEM_PERIOD_MS, EMBLEM_BOX = 60, 4000, 36
ICON_SIZE, ICON_BOX = 18, 22
# name: (WMO code, is_day)
ICONS = {
    "clear_day": (0, True), "clear_night": (0, False),
    "partly_day": (2, True), "partly_night": (2, False),
    "overcast": (3, True), "fog": (45, True), "drizzle": (51, True), "rain": (61, True),
    "showers_day": (80, True), "snow": (71, True), "storm": (95, True),
}


def rgb565_be(im) -> bytes:
    raw = im.convert("RGB").tobytes()
    out = bytearray()
    for i in range(0, len(raw), 3):
        r, g, b = raw[i], raw[i + 1], raw[i + 2]
        v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        out += bytes((v >> 8, v & 0xFF))
    return bytes(out)


def c_array(name: str, data: bytes) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 24]) for i in range(0, len(data), 24)]
    return f"static const uint8_t {name}[{len(data)}] __attribute__((aligned(4))) = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def emblem_frame(i: int):
    """Frame i of the loop: a soft light travels clockwise round the five wings (one per
    screen), one lap per loop; the wings it isn't on rest at a low glow."""
    pos = 5 * i / EMBLEM_FRAMES                     # where the light is, in wings
    lit = []
    for w in range(5):
        d = abs((w + 0.5 - pos + 2.5) % 5 - 2.5)    # circular distance to the light
        lit.append(0.38 + 0.62 * math.exp(-(d / 0.85) ** 2))
    return mark.render(EMBLEM_BOX, lit=lit, bg="#000000", dim_to="#000000")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    parts = ["/* Generated by tools/gen_assets.py. Do not edit. */", '#include "images.h"', ""]
    descs = []
    for i in range(EMBLEM_FRAMES):
        parts.append(c_array(f"emblem_{i:02d}", rgb565_be(emblem_frame(i))))
        descs.append(f"{{ {EMBLEM_BOX}, {EMBLEM_BOX}, emblem_{i:02d} }}")
    parts.append("const hud_image_t img_emblem[IMG_EMBLEM_FRAMES] = {\n    " + ",\n    ".join(descs) + "\n};\n")
    for name, (code, day) in ICONS.items():
        c = Canvas(ICON_BOX, ICON_BOX, bg=CANVAS)
        weather(c, ICON_BOX / 2, ICON_BOX / 2, ICON_SIZE, code, day)
        parts.append(c_array(f"icon_{name}", rgb565_be(c.finish())))
        parts.append(f"const hud_image_t img_icon_{name} = {{ {ICON_BOX}, {ICON_BOX}, icon_{name} }};\n")
    (OUT / "images.c").write_text("\n".join(parts), encoding="utf-8")

    header = ["/* Generated by tools/gen_assets.py. Do not edit. */", "#pragma once", '#include "hud.h"', "",
              "/* the Pentadeck mark, a light travelling round its wings: one loop */",
              f"#define IMG_EMBLEM_FRAMES {EMBLEM_FRAMES}",
              f"#define IMG_EMBLEM_PERIOD_MS {EMBLEM_PERIOD_MS}",
              f"#define IMG_EMBLEM_SIZE {EMBLEM_BOX}",
              "extern const hud_image_t img_emblem[IMG_EMBLEM_FRAMES];", "",
              f"/* weather icons, {ICON_BOX}x{ICON_BOX}, drawn on black */"]
    header += [f"extern const hud_image_t img_icon_{n};" for n in ICONS]
    (OUT / "images.h").write_text("\n".join(header) + "\n", encoding="utf-8")
    print(f"images.c: {EMBLEM_FRAMES} emblem frames + {len(ICONS)} icons")


if __name__ == "__main__":
    main()
